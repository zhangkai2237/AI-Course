def notes_from(slide, intro, *headings):
    chunks = []
    for key in (intro,) + headings:
        if key in NOTES and NOTES[key] not in chunks:
            chunks.append(NOTES[key])
    if not chunks:
        chunks.append("围绕本页标题解释关键判断，并结合课堂提问确认学员是否理解。")
    dk.speaker_notes(slide, "\n\n".join(chunks) + f"\n\n[课程规划来源]\n{PLAN}")


m.notes_from = notes_from


