    stages = flow
    x0, y, total_w, gap = 0.84, 2.16, 11.46, 0.16
    cw = (total_w - gap * (len(stages) - 1)) / len(stages)
    for i, (t, b) in enumerate(stages):
        x = x0 + i * (cw + gap)
        m.card(s, x, y, cw, 2.36, t, b, f"{i+1:02d}", accent, 14.5, 11.8)
