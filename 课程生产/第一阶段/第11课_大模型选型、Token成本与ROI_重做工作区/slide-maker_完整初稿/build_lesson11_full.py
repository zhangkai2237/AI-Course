def txt(slide, x, y, w, h, value, size, color=TEXT, bold=False,
        align=dk.PP_ALIGN.LEFT, anchor=dk.MSO_ANCHOR.TOP, wrap=True):
    return dk.text(
        slide, x, y, w, h,
        [[(str(value), size, color, bold, False, "Helvetica Neue", "Hiragino Sans GB")]],
        align=align, anchor=anchor, space_after=0, wrap=wrap,
    )


def rich(slide, x, y, w, h, lines, align=dk.PP_ALIGN.LEFT,
         anchor=dk.MSO_ANCHOR.TOP, line_spacing=1.0):
    runs = []
    for line in lines:
        row = []
        for value, size, color, bold in line:
            row.append((str(value), size, color, bold, False, "Helvetica Neue", "Hiragino Sans GB"))
        runs.append(row)
    return dk.text(slide, x, y, w, h, runs, align=align, anchor=anchor,
                   space_after=3, line_spacing=line_spacing)


