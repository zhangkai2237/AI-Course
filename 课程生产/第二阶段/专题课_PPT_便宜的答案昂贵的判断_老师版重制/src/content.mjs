function n(minutes, objective, script, action, reaction, followup, caution, transition, source) {
  return teacherNotes({ minutes, objective, script, action, reaction, followup, caution, transition, source });
}
function s(id, act, type, title, minutes, content, source, extras = {}) {
  const objective = extras.objective || `理解“${title}”并完成课堂判断。`;
  const script = extras.script || `请先看页面，不急着抄结论。我们要判断：这里哪些是事实，哪些只是看起来专业。${content.key ? `本页关键句是：${content.key}` : ""}`;
  const action = extras.action || "停留5秒让学员阅读；点名1—2位学员给出判断，再显示结论。";
  const reaction = extras.reaction || "学员能指出至少一个可核验点，或承认当前证据不足。";
  const followup = extras.followup || "你依据什么这样判断？如果要把它写进作品集，还缺哪份证据？";
  const caution = extras.caution || (extras.publicCase ? "本页客服内容仅为公共模拟案例；不得表述为真实上线、真实用户或真实成效。" : "不要替学员补数据、补经历；只能使用本人可举证的事实。 ");
  const transition = extras.transition || "把这一判断带到下一页，继续核对表达与证据。";
  return { id, act, type, title, minutes, source, ...content, ...extras, notes: n(minutes, objective, script, action, reaction, followup, caution, transition, source) };
}

